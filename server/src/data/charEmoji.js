/**
 * 为一个字挑选配图 emoji
 * @param {{hanzi:string, meaning?:string, words?:string}} char
 * @returns {string} emoji；未命中返回 ''
 */
export function pickEmoji(char) {
  if (!char) return '';
  const hanzi = String(char.hanzi || '').trim();
  if (CURATED[hanzi]) return CURATED[hanzi];

  const text = `${char.meaning || ''} ${char.words || ''}`;
  for (const [re, emoji] of RULES) {
    if (re.test(text)) return emoji;
  }
  return '';
}
